CREATE TABLE IF NOT EXISTS "pay_schedule_periods" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"isolved_group" text NOT NULL,
	"group_key" text NOT NULL,
	"isolved_code" text,
	"period_number" integer NOT NULL,
	"period_start" date NOT NULL,
	"period_end" date NOT NULL,
	"run_date" date NOT NULL,
	"check_date" date NOT NULL,
	"note" text,
	"source" text DEFAULT 'isolved' NOT NULL,
	"added_by" uuid REFERENCES "staff"("id"),
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "pay_schedule_periods_uq" UNIQUE("group_key", "period_start"),
	CONSTRAINT "pay_schedule_periods_shape" CHECK ("period_end" = "period_start" + 13 AND extract(dow from "period_start") = 0 AND "run_date" >= "period_end" AND "check_date" >= "run_date" AND "check_date" <= "period_end" + 31 AND "period_number" >= 1),
	CONSTRAINT "pay_schedule_periods_source" CHECK ("source" IN ('isolved', 'admin')),
	CONSTRAINT "pay_schedule_periods_code" CHECK ("isolved_code" IS NULL OR "isolved_code" ~ '^[A-Z0-9]{1,4}$'),
	CONSTRAINT "pay_schedule_periods_note_len" CHECK ("note" IS NULL OR char_length("note") <= 300)
);--> statement-breakpoint
CREATE OR REPLACE FUNCTION "pay_schedule_no_overlap"() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	IF EXISTS (
		SELECT 1 FROM "pay_schedule_periods" o
		WHERE o."group_key" = NEW."group_key" AND o."id" <> NEW."id" AND o."period_start" <= NEW."period_end" AND o."period_end" >= NEW."period_start"
	) THEN
		RAISE EXCEPTION 'pay schedule periods for % overlap at %', NEW."group_key", NEW."period_start";
	END IF;
	RETURN NEW;
END $$;--> statement-breakpoint
