export type Lang = "en" | "es";
export type CopyKey = keyof typeof en;

const I18n = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: (key: CopyKey) => string }>({
  lang: "en",
  setLang: () => undefined,
  t: (key) => en[key],
});

const LANG_KEY = "rayz.lang";

export function I18nProvider({ children, initial = "en" }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLangState] = useState<Lang>(initial);
  useEffect(() => {
    if (typeof localStorage === "undefined") return;
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "es") setLangState(saved);
  }, []);
  const setLang = (next: Lang) => {
    setLangState(next);
    if (typeof localStorage !== "undefined") localStorage.setItem(LANG_KEY, next);
  };
  const value = useMemo(() => ({ lang, setLang, t: (key: CopyKey) => (lang === "es" ? es[key] : en[key]) }), [lang]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useI18n() {
  return useContext(I18n);
}

