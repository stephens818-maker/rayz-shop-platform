import type { SyncType } from "@/domain/brand-sync";

/**
 * What every table, and every column of the tables that mix settings with other things, is to the
 * brand change scope. tests/db/brand-sync-coverage.test.ts fails on a table or column that isn't
 * here, so a new setting can't be added without saying which sync type carries it to the shops.
 *
 * - sync: a brand-level value that reaches the shops through the brand change scope (these types).
 * - list: rows of a brand list (src/server/brand-sync/lists.ts); which shops offer each is the list type.
 * - picker: the brand makes it and picks its shops on it (a blast's locations, a plan's shops).
 * - shared: one record every shop shares (a product's SKU), so a change is at every shop at once.
 * - shop: a shop's own (its address, its card readers); there's no brand value to send.
 * - person: one person's own (their pay, their saved reports).
 * - record: something that happened (a sale, a message, a log line), not a setting.
 * - structure: how the brand is organised (regions, owner entities, groups).
 * - engine: the brand change scope's own bookkeeping.
 */
export type CoverageKind = "sync" | "list" | "picker" | "shared" | "shop" | "person" | "record" | "structure" | "engine";
export type Coverage = { kind: "sync"; types: readonly SyncType[]; why?: string } | { kind: Exclude<CoverageKind, "sync">; why: string };

const sync = (types: SyncType[], why?: string): Coverage => ({ kind: "sync", types, ...(why ? { why } : {}) });
const is = (kind: Exclude<CoverageKind, "sync">, why: string): Coverage => ({ kind, why });

